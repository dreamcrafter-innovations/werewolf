export const makeShadow = (color, radius = 10, opacity = 0.4) => ({
  shadowColor:   color,
  shadowOffset:  { width: 0, height: 0 },
  shadowOpacity: opacity,
  shadowRadius:  radius,
  elevation:     Math.round(radius * 0.6),
});
